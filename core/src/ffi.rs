/// Resolves bridged sprite occurrences into substitution instructions.
pub fn sprite_sub_resolve(
    ts: &crate::vram_sprite::SpriteSubstitutor,
    occs: &[ffi::SpriteOccurrence],
) -> Vec<ffi::SpriteSub> {
    let native: Vec<crate::vram_sprite::SpriteOccurrence> = occs
        .iter()
        .map(|o| crate::vram_sprite::SpriteOccurrence {
            hash: o.hash,
            anim_group_id: o.anim_group_id,
            w_tiles: o.w_tiles,
            h_tiles: o.h_tiles,
            screen_x: o.screen_x,
            screen_y: o.screen_y,
            link: o.link,
            palette: o.palette,
            priority: o.priority,
            slot: 0, // ruta cxx (resolve) no usa el slot SAT
            hflip: 0,
            vflip: 0, // CU-AN-11 (ruta cxx no aplica flip)
        })
        .collect();

    ts.resolve(&native)
        .into_iter()
        .map(|s| ffi::SpriteSub {
            asset_path: s.asset_path,
            screen_x: s.screen_x,
            screen_y: s.screen_y,
            w_tiles: s.w_tiles,
            h_tiles: s.h_tiles,
        })
        .collect()
}
